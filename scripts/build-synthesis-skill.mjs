#!/usr/bin/env node
// Builds what the Synthesis authoring skill and the app's contract drafting share, from one source:
//   skills/lc-synthesis/references/language.md and diagnostics.md  (written by hand)
//   skills/lc-synthesis/references/examples/python-slug/...         (written by hand, its flow derived)
//   skills/lc-synthesis/references/examples/typescript-rate-limiter (the app's rate limiter template)
//   skills/lc-synthesis/references/examples/cpp-ability-system      (copied from examples/synthesis-ability-system)
//   skills/lc-synthesis/scripts/check.mjs                           (the offline check, bundled)
//   src/synthesis/knowledge/pack.generated.ts                       (the reference, fixes and examples for prompts)
// `--check` writes nothing and fails when a generated file is not what this script would write.
import { build } from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skill = path.join(repo, "skills/lc-synthesis");
const examples = path.join(skill, "references/examples");
const check = process.argv.includes("--check");
const outputs = new Map();
const out = (file, text) => outputs.set(path.join(repo, file), text);
const read = file => fs.readFile(path.join(repo, file), "utf8");

// The app's templates, compiled on the fly (no build needed).
const bundled = await build({ entryPoints: [path.join(repo, "src/synthesis/templates.ts")], bundle: true, format: "esm", platform: "node", write: false, logLevel: "silent" });
const templates = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);

const rateLimiter = templates.rateLimiterTemplate();
const rl = "skills/lc-synthesis/references/examples/typescript-rate-limiter/Synthesis/RateLimiter";
out(`${rl}/RateLimiter.lcspec`, rateLimiter.spec);
out(`${rl}/RateLimiter.lcflow`, rateLimiter.flow);
for (const [file, text] of Object.entries(rateLimiter.tests)) out(`${rl}/${file}`, text);

const slug = "skills/lc-synthesis/references/examples/python-slug/Synthesis/Slug";
out(`${slug}/Slug.lcflow`, templates.flowTemplate("Slug", ["src/slug.py"], { output: "slug", model: { kind: "local", maxSize: "6GiB", prefer: "coder" } }));

const ability = "examples/synthesis-ability-system";
const cpp = "skills/lc-synthesis/references/examples/cpp-ability-system";
for (const file of ["Synthesis/AbilitySystem/AbilitySystem.lcspec", "Synthesis/AbilitySystem/AbilitySystem.lcflow", "Synthesis/AbilitySystem/tests/ability_system_test.cpp", "ability-system/include/AbilitySystem.h"]) {
  out(`${cpp}/${file}`, await read(`${ability}/${file}`));
}

// The offline check as one script with no dependencies: node check.mjs [<module.lcspec | folder>] [--json].
const checker = await build({
  stdin: { contents: `import { runCheckCommand } from "./src/synthesis/checkFolder.ts";\nprocess.exitCode = await runCheckCommand(process.argv.slice(2));\n`, resolveDir: repo, sourcefile: "check-entry.ts", loader: "ts" },
  bundle: true, format: "esm", platform: "node", target: "node18", write: false, logLevel: "silent", legalComments: "none",
  banner: { js: "#!/usr/bin/env node\n// Local Cognitive Synthesis: checks modules offline (generated by scripts/build-synthesis-skill.mjs; Elastic License 2.0)." }
});
out("skills/lc-synthesis/scripts/check.mjs", checker.outputFiles[0].text);

// The prompt pack: the same reference, each code's fix, and the examples by language.
const language = await read("skills/lc-synthesis/references/language.md");
const fixes = {};
for (const line of (await read("skills/lc-synthesis/references/diagnostics.md")).split("\n")) {
  const row = /^\| `([A-Z_]+)`(?: \/ `([A-Z_]+)`)?(?: \(warning\))? \| (.+) \|$/.exec(line);
  if (row) for (const code of [row[1], row[2]].filter(Boolean)) fixes[code] = row[3].replace(/\\\|/g, "|");
}
// A folder as it will be: its files on disk, with what this script writes there in their place.
const listFiles = async folder => {
  const found = {};
  const walk = async relative => {
    for (const entry of await fs.readdir(path.join(repo, folder, relative), { withFileTypes: true }).catch(() => [])) {
      const next = relative ? `${relative}/${entry.name}` : entry.name;
      if (entry.isDirectory()) await walk(next); else found[next] = await fs.readFile(path.join(repo, folder, next), "utf8");
    }
  };
  await walk("");
  const prefix = path.join(repo, folder) + path.sep;
  for (const [file, text] of outputs) if (file.startsWith(prefix)) found[path.relative(path.join(repo, folder), file).split(path.sep).join("/")] = text;
  return found;
};
const example = async (language, base, name, frozenFolder) => {
  const all = await listFiles(`skills/lc-synthesis/references/examples/${base}/Synthesis/${name}`);
  const tests = Object.fromEntries(Object.entries(all).filter(([file]) => file.startsWith("tests/")).sort(([a], [b]) => a.localeCompare(b)));
  const frozen = frozenFolder ? await listFiles(`skills/lc-synthesis/references/examples/${base}/${frozenFolder}`) : {};
  return { language, name, spec: all[`${name}.lcspec`], flow: all[`${name}.lcflow`], tests, frozen };
};
const pack = {
  examples: [
    await example("TypeScript", "typescript-rate-limiter", "RateLimiter"),
    await example("Python", "python-slug", "Slug"),
    await example("Cpp", "cpp-ability-system", "AbilitySystem", "ability-system")
  ]
};
out("src/synthesis/knowledge/pack.generated.ts", `// Generated by scripts/build-synthesis-skill.mjs from skills/lc-synthesis: edit those files and run
// \`npm run build:skill\`, never this one. The same text is the authoring skill's reference.

/** The condensed language reference (skills/lc-synthesis/references/language.md). */
export const LANGUAGE_REFERENCE = ${JSON.stringify(language)};

/** Each diagnostic code's fix (skills/lc-synthesis/references/diagnostics.md). */
export const DIAGNOSTIC_FIXES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(Object.entries(fixes).sort()), null, 2)};

export interface PackExample { language: "TypeScript" | "Python" | "Cpp"; name: string; spec: string; flow: string; tests: Record<string, string>; frozen: Record<string, string> }
/** Complete modules that pass their gates, one per language (skills/lc-synthesis/references/examples). */
export const EXAMPLES: readonly PackExample[] = ${JSON.stringify(pack.examples, null, 2)};
`);

const stale = [];
for (const [file, text] of outputs) {
  const now = await fs.readFile(file, "utf8").catch(() => undefined);
  if (now === text) continue;
  if (check) { stale.push(path.relative(repo, file)); continue; }
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text, file.endsWith("check.mjs") ? { mode: 0o755 } : undefined);
  console.log(`wrote ${path.relative(repo, file)}`);
}
if (stale.length) { console.error(`Out of date (run npm run build:skill):\n${stale.join("\n")}`); process.exit(1); }
